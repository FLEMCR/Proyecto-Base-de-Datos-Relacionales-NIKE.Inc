"""Genera los dos scripts DDL del modelo fisico (SQL Server y Oracle).

Incluye lo que el docente pidio ver en la capa fisica:
  * IDENTITY en las claves primarias simples (SQL Server) / GENERATED AS IDENTITY (Oracle)
  * DEFAULT en las columnas que nacen con un valor
  * CHECK en cantidades, precios, estados, correo y telefono
  * cuatro campos de auditoria en todas las tablas
  * las 11 claves foraneas y las claves primarias compuestas
"""
import modelo_final as M

ESP = "    "


def tipo_sql(col, motor):
    nombre, tipo, largo, marca, opc = col
    if tipo == "VARCHAR":
        return ("VARCHAR2(%d)" % largo) if motor == "oracle" else ("VARCHAR(%d)" % largo)
    if tipo == "DECIMAL":
        return ("NUMBER(%d,%d)" % largo) if motor == "oracle" else ("DECIMAL(%d,%d)" % largo)
    if tipo == "INTEGER":
        return "NUMBER(10)" if motor == "oracle" else "INTEGER"
    return "DATE"


def tipo_auditoria(tipo, largo, motor):
    if tipo == "VARCHAR":
        return ("VARCHAR2(%d)" % largo) if motor == "oracle" else ("VARCHAR(%d)" % largo)
    return "TIMESTAMP" if motor == "oracle" else "DATETIME"


def condicion(cond, motor):
    """Traduce las dos validaciones que no se escriben igual en los dos motores."""
    if motor == "oracle":
        cond = cond.replace("telefono NOT LIKE '%[^0-9]%' AND LEN(telefono) BETWEEN 6 AND 15",
                            "REGEXP_LIKE(telefono, '^[0-9]{6,15}$')")
        cond = cond.replace("correo_electronico LIKE '%_@_%._%'",
                            "REGEXP_LIKE(correo_electronico, '^[A-Za-z0-9._%-]+@[A-Za-z0-9.-]+[.][A-Za-z]{2,}$')")
        cond = cond.replace("CURRENT_TIMESTAMP", "SYSTIMESTAMP")
    return cond


def valor_default(valor, motor):
    if motor == "sqlserver":
        return {"CURRENT_DATE": "CAST(GETDATE() AS DATE)",
                "CURRENT_TIMESTAMP": "GETDATE()"}.get(valor, valor)
    if motor == "oracle":
        return {"CURRENT_DATE": "SYSDATE", "CURRENT_TIMESTAMP": "SYSTIMESTAMP",
                "SYSTEM_USER": "USER"}.get(valor, valor)
    return valor


def bloque_columnas(tabla, motor):
    """Columnas propias + auditoria, ya con IDENTITY / DEFAULT / NOT NULL."""
    lineas = []
    defs = {col: (valor, motivo) for col, valor, motivo in M.defaults_de(tabla)}
    for col in M.TABLES[tabla]["cols"]:
        nombre, tipo, largo, marca, opc = col
        t = tipo_sql(col, motor)
        if M.es_identidad(tabla, nombre):
            if motor == "oracle":
                t += " GENERATED BY DEFAULT ON NULL AS IDENTITY"
            else:
                t = "INT IDENTITY(1,1)"
        txt = "%-28s %s" % (nombre, t)
        if nombre in defs:
            txt += " DEFAULT %s" % valor_default(defs[nombre][0], motor)
        if not opc:
            txt += " NOT NULL"
        lineas.append(ESP + txt)
    for nombre, tipo, largo, valor, motivo in M.AUDITORIA:
        t = tipo_auditoria(tipo, largo, motor)
        txt = "%-28s %s" % (nombre, t)
        if valor != "NULL":
            txt += " DEFAULT %s" % valor_default(valor, motor)
        if valor != "NULL":
            txt += " NOT NULL"
        lineas.append(ESP + txt)
    return ",\n".join(lineas)


def restricciones(tabla, motor):
    """PK y CHECK, escritos dentro del CREATE TABLE."""
    out = [ESP + "CONSTRAINT %s_PK PRIMARY KEY (%s)" % (tabla, ", ".join(M.pk_cols(tabla)))]
    for nombre, cond, motivo in M.checks_de(tabla):
        out.append(ESP + "CONSTRAINT %s CHECK (%s)" % (nombre, condicion(cond, motor)))
    return ",\n".join(out)


# --------------------------------------------------------------------- SQL Server
def sqlserver():
    o = []
    o += ["-- =====================================================================",
          "-- BD NIKE Inc. | Grupo 05 | Diseno de Bases de Datos Relacionales",
          "-- MODELO FISICO - Microsoft SQL Server (SSMS)",
          "-- 10 tablas | 11 claves foraneas | PK compuestas",
          "-- IDENTITY | DEFAULT | CHECK | 4 campos de auditoria",
          "-- Ninguna columna calculada: no hay total, no hay igv, no hay vistas.",
          "-- =====================================================================",
          "IF DB_ID('NIKE_INC_BD') IS NOT NULL",
          "    DROP DATABASE NIKE_INC_BD;",
          "GO",
          "CREATE DATABASE NIKE_INC_BD;",
          "GO",
          "USE NIKE_INC_BD;",
          "GO",
          ""]
    for i, t in enumerate(M.ORDER, 1):
        o.append("-- ---------------------------------------------------------------------")
        o.append("-- %d. %s - %s" % (i, t, M.TABLES[t]["rol"]))
        o.append("-- %s" % M.TABLES[t]["proposito"])
        o.append("-- ---------------------------------------------------------------------")
        o.append("CREATE TABLE %s (" % t)
        o.append(bloque_columnas(t, "sqlserver") + ",")
        o.append(restricciones(t, "sqlserver"))
        o.append(");")
        o.append("GO")
        o.append("")
    o.append("-- =====================================================================")
    o.append("-- CLAVES FORANEAS (11)")
    o.append("-- =====================================================================")
    for nombre, hija, col, padre, pkc, rel in M.FKS:
        o.append("ALTER TABLE %s" % hija)
        o.append("%sADD CONSTRAINT %s FOREIGN KEY (%s)" % (ESP, nombre, col))
        o.append("%sREFERENCES %s (%s) ON DELETE NO ACTION ON UPDATE NO ACTION;" % (ESP, padre, pkc))
        o.append("%s-- relacion %s del MER" % (ESP, rel))
        o.append("GO")
    o.append("")
    o.append("-- =====================================================================")
    o.append("-- COMPROBACION")
    o.append("-- =====================================================================")
    o.append("EXEC sp_help 'STOCK_ALMACEN';        -- se ven IDENTITY, DEFAULT, CHECK y auditoria")
    o.append("SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, IS_NULLABLE")
    o.append("FROM INFORMATION_SCHEMA.COLUMNS ORDER BY TABLE_NAME, ORDINAL_POSITION;")
    o.append("GO")
    o.append("")
    o.append("-- =====================================================================")
    o.append("-- DATOS DE PRUEBA: el INSERT no envia las claves ni las auditorias,")
    o.append("-- las genera IDENTITY y los DEFAULT.")
    o.append("-- =====================================================================")
