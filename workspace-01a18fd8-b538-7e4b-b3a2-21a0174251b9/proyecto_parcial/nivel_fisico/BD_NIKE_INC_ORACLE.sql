DROP TABLE CLIENTE CASCADE CONSTRAINTS;
DROP TABLE CATEGORIA CASCADE CONSTRAINTS;
DROP TABLE ALMACEN CASCADE CONSTRAINTS;
DROP TABLE LOCAL CASCADE CONSTRAINTS;
DROP TABLE PRODUCTO CASCADE CONSTRAINTS;
DROP TABLE PEDIDO CASCADE CONSTRAINTS;
DROP TABLE SUMINISTRO CASCADE CONSTRAINTS;
DROP TABLE DETALLE_VENTA CASCADE CONSTRAINTS;
DROP TABLE STOCK_ALMACEN CASCADE CONSTRAINTS;
DROP TABLE DETALLE_SUMINISTRO CASCADE CONSTRAINTS;

-- ---------------------------------------------------------------------
-- 1. CLIENTE - Maestra
-- Registra al comprador; un cliente puede hacer muchos pedidos.
-- ---------------------------------------------------------------------
CREATE TABLE CLIENTE (
    id_cliente                   NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nombre                       VARCHAR2(80) NOT NULL,
    correo_electronico           VARCHAR2(80) NOT NULL,
    telefono                     VARCHAR2(15) NOT NULL,
    telefono_secundario          VARCHAR2(15),
    direccion                    VARCHAR2(120) NOT NULL,
    usuario_creacion             VARCHAR2(30) DEFAULT USER NOT NULL,
    fecha_creacion               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    usuario_modificacion         VARCHAR2(30),
    fecha_modificacion           TIMESTAMP,
    CONSTRAINT CLIENTE_PK PRIMARY KEY (id_cliente),
    CONSTRAINT CK_CLIENTE_CORREO CHECK (REGEXP_LIKE(correo_electronico, '^[A-Za-z0-9._%-]+@[A-Za-z0-9.-]+[.][A-Za-z]{2,}$')),
    CONSTRAINT CK_CLIENTE_TELEFONO CHECK (REGEXP_LIKE(telefono, '^[0-9]{6,15}$'))
);

-- ---------------------------------------------------------------------
-- 2. CATEGORIA - Maestra
-- Clasifica los productos en una linea comercial.
-- ---------------------------------------------------------------------
CREATE TABLE CATEGORIA (
    id_categoria                 NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nombre                       VARCHAR2(50) NOT NULL,
    descripcion                  VARCHAR2(150),
    usuario_creacion             VARCHAR2(30) DEFAULT USER NOT NULL,
    fecha_creacion               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    usuario_modificacion         VARCHAR2(30),
    fecha_modificacion           TIMESTAMP,
    CONSTRAINT CATEGORIA_PK PRIMARY KEY (id_categoria)
);

-- ---------------------------------------------------------------------
-- 3. ALMACEN - Maestra
-- Centro de distribucion que guarda stock y abastece a los locales.
-- ---------------------------------------------------------------------
CREATE TABLE ALMACEN (
    id_almacen                   NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nombre_almacen               VARCHAR2(50) NOT NULL,
    ubicacion                    VARCHAR2(120) NOT NULL,
    usuario_creacion             VARCHAR2(30) DEFAULT USER NOT NULL,
    fecha_creacion               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    usuario_modificacion         VARCHAR2(30),
    fecha_modificacion           TIMESTAMP,
    CONSTRAINT ALMACEN_PK PRIMARY KEY (id_almacen)
);

-- ---------------------------------------------------------------------
-- 4. LOCAL - Maestra
-- Tienda fisica que recibe mercaderia de los centros de distribucion.
-- ---------------------------------------------------------------------
CREATE TABLE LOCAL (
    id_local                     NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nombre_local                 VARCHAR2(50) NOT NULL,
    direccion_local              VARCHAR2(120) NOT NULL,
    usuario_creacion             VARCHAR2(30) DEFAULT USER NOT NULL,
    fecha_creacion               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    usuario_modificacion         VARCHAR2(30),
    fecha_modificacion           TIMESTAMP,
    CONSTRAINT LOCAL_PK PRIMARY KEY (id_local)
);

-- ---------------------------------------------------------------------
-- 5. PRODUCTO - Maestra
-- Catalogo de modelos; las tallas y colores viven en el stock y en el detalle.
-- ---------------------------------------------------------------------
CREATE TABLE PRODUCTO (
    id_producto                  NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nombre                       VARCHAR2(80) NOT NULL,
    especificaciones             VARCHAR2(150),
    precio_unitario_base         NUMBER(10,2) NOT NULL,
    estado                       VARCHAR2(20) DEFAULT 'DISPONIBLE' NOT NULL,
    CATEGORIA_id_categoria       NUMBER(10) NOT NULL,
    usuario_creacion             VARCHAR2(30) DEFAULT USER NOT NULL,
    fecha_creacion               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    usuario_modificacion         VARCHAR2(30),
    fecha_modificacion           TIMESTAMP,
    CONSTRAINT PRODUCTO_PK PRIMARY KEY (id_producto),
    CONSTRAINT CK_PRODUCTO_PRECIO CHECK (precio_unitario_base > 0),
    CONSTRAINT CK_PRODUCTO_ESTADO CHECK (estado IN ('DISPONIBLE', 'AGOTADO', 'DESCONTINUADO'))
);

-- ---------------------------------------------------------------------
-- 6. PEDIDO - Transaccional
-- Cabecera de la compra: quien compra, cuando, como paga y con que suministro se atiende.
-- ---------------------------------------------------------------------
CREATE TABLE PEDIDO (
    id_pedido                    NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    fecha                        DATE DEFAULT SYSDATE NOT NULL,
    metodo_pago                  VARCHAR2(30) DEFAULT 'Tarjeta de Credito' NOT NULL,
    CLIENTE_id_cliente           NUMBER(10) NOT NULL,
    SUMINISTRO_id_suministro     NUMBER(10) NOT NULL,
    usuario_creacion             VARCHAR2(30) DEFAULT USER NOT NULL,
    fecha_creacion               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    usuario_modificacion         VARCHAR2(30),
    fecha_modificacion           TIMESTAMP,
    CONSTRAINT PEDIDO_PK PRIMARY KEY (id_pedido)
);

-- ---------------------------------------------------------------------
-- 7. SUMINISTRO - Transaccional
-- Cabecera del abastecimiento: de que almacen sale y a que local llega.
-- ---------------------------------------------------------------------
CREATE TABLE SUMINISTRO (
    id_suministro                NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    fecha_suministro             DATE DEFAULT SYSDATE NOT NULL,
    estado_despacho              VARCHAR2(20) DEFAULT 'PROGRAMADO' NOT NULL,
    ALMACEN_id_almacen           NUMBER(10) NOT NULL,
    LOCAL_id_local               NUMBER(10) NOT NULL,
    usuario_creacion             VARCHAR2(30) DEFAULT USER NOT NULL,
    fecha_creacion               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    usuario_modificacion         VARCHAR2(30),
    fecha_modificacion           TIMESTAMP,
    CONSTRAINT SUMINISTRO_PK PRIMARY KEY (id_suministro),
    CONSTRAINT CK_SUMINISTRO_ESTADO CHECK (estado_despacho IN ('PROGRAMADO', 'EN RUTA', 'ENTREGADO'))
);

-- ---------------------------------------------------------------------
-- 8. DETALLE_VENTA - Intermedia
-- Resuelve CONTIENE: que producto, en que talla y color, cuanto y a que precio.
-- ---------------------------------------------------------------------
CREATE TABLE DETALLE_VENTA (
    PEDIDO_id_pedido             NUMBER(10) NOT NULL,
    PRODUCTO_id_producto         NUMBER(10) NOT NULL,
    talla_elegida                VARCHAR2(10) NOT NULL,
    color_elegido                VARCHAR2(30) NOT NULL,
    cantidad                     NUMBER(10) DEFAULT 1 NOT NULL,
    precio_unitario_aplicado     NUMBER(10,2) NOT NULL,
    usuario_creacion             VARCHAR2(30) DEFAULT USER NOT NULL,
    fecha_creacion               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    usuario_modificacion         VARCHAR2(30),
    fecha_modificacion           TIMESTAMP,
    CONSTRAINT DETALLE_VENTA_PK PRIMARY KEY (PEDIDO_id_pedido, PRODUCTO_id_producto, talla_elegida, color_elegido),
    CONSTRAINT CK_DETALLE_VENTA_CANTIDAD CHECK (cantidad > 0),
    CONSTRAINT CK_DETALLE_VENTA_PRECIO CHECK (precio_unitario_aplicado > 0)
);

-- ---------------------------------------------------------------------
-- 9. STOCK_ALMACEN - Intermedia
-- Resuelve ALMACENA: existencias por almacen, producto, talla y color.
-- ---------------------------------------------------------------------
CREATE TABLE STOCK_ALMACEN (
    ALMACEN_id_almacen           NUMBER(10) NOT NULL,
    PRODUCTO_id_producto         NUMBER(10) NOT NULL,
    talla                        VARCHAR2(10) NOT NULL,
    color                        VARCHAR2(30) NOT NULL,
    stock_actual                 NUMBER(10) DEFAULT 0 NOT NULL,
    stock_minimo                 NUMBER(10) DEFAULT 0 NOT NULL,
    usuario_creacion             VARCHAR2(30) DEFAULT USER NOT NULL,
    fecha_creacion               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    usuario_modificacion         VARCHAR2(30),
    fecha_modificacion           TIMESTAMP,
    CONSTRAINT STOCK_ALMACEN_PK PRIMARY KEY (ALMACEN_id_almacen, PRODUCTO_id_producto, talla, color),
    CONSTRAINT CK_STOCK_ALMACEN_ACTUAL CHECK (stock_actual >= 0),
    CONSTRAINT CK_STOCK_ALMACEN_MINIMO CHECK (stock_minimo >= 0)
);

-- ---------------------------------------------------------------------
-- 10. DETALLE_SUMINISTRO - Intermedia
-- Resuelve INCLUYE: que productos y cantidades lleva cada suministro.
-- ---------------------------------------------------------------------
CREATE TABLE DETALLE_SUMINISTRO (
    SUMINISTRO_id_suministro     NUMBER(10) NOT NULL,
    PRODUCTO_id_producto         NUMBER(10) NOT NULL,
    talla                        VARCHAR2(10) NOT NULL,
    color                        VARCHAR2(30) NOT NULL,
    cantidad                     NUMBER(10) DEFAULT 1 NOT NULL,
    usuario_creacion             VARCHAR2(30) DEFAULT USER NOT NULL,
    fecha_creacion               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    usuario_modificacion         VARCHAR2(30),
    fecha_modificacion           TIMESTAMP,
    CONSTRAINT DETALLE_SUMINISTRO_PK PRIMARY KEY (SUMINISTRO_id_suministro, PRODUCTO_id_producto, talla, color),
    CONSTRAINT CK_DETALLE_SUMINISTRO_CANTIDAD CHECK (cantidad > 0)
);

-- =====================================================================
-- CLAVES FORANEAS (11)
-- =====================================================================
ALTER TABLE PRODUCTO ADD CONSTRAINT PRODUCTO_CATEGORIA_FK FOREIGN KEY (CATEGORIA_id_categoria) REFERENCES CATEGORIA (id_categoria);
-- relacion CLASIFICA del MER
ALTER TABLE PEDIDO ADD CONSTRAINT PEDIDO_CLIENTE_FK FOREIGN KEY (CLIENTE_id_cliente) REFERENCES CLIENTE (id_cliente);
-- relacion REALIZA del MER
ALTER TABLE PEDIDO ADD CONSTRAINT PEDIDO_SUMINISTRO_FK FOREIGN KEY (SUMINISTRO_id_suministro) REFERENCES SUMINISTRO (id_suministro);
-- relacion PROVEE del MER
ALTER TABLE SUMINISTRO ADD CONSTRAINT SUMINISTRO_ALMACEN_FK FOREIGN KEY (ALMACEN_id_almacen) REFERENCES ALMACEN (id_almacen);
-- relacion ABASTECE del MER
ALTER TABLE SUMINISTRO ADD CONSTRAINT SUMINISTRO_LOCAL_FK FOREIGN KEY (LOCAL_id_local) REFERENCES LOCAL (id_local);
-- relacion RECIBE del MER
ALTER TABLE DETALLE_VENTA ADD CONSTRAINT DETALLE_VENTA_PEDIDO_FK FOREIGN KEY (PEDIDO_id_pedido) REFERENCES PEDIDO (id_pedido);
-- relacion CONTIENE del MER
ALTER TABLE DETALLE_VENTA ADD CONSTRAINT DETALLE_VENTA_PRODUCTO_FK FOREIGN KEY (PRODUCTO_id_producto) REFERENCES PRODUCTO (id_producto);
-- relacion CONTIENE del MER
ALTER TABLE STOCK_ALMACEN ADD CONSTRAINT STOCK_ALMACEN_ALMACEN_FK FOREIGN KEY (ALMACEN_id_almacen) REFERENCES ALMACEN (id_almacen);
-- relacion ALMACENA del MER
ALTER TABLE STOCK_ALMACEN ADD CONSTRAINT STOCK_ALMACEN_PRODUCTO_FK FOREIGN KEY (PRODUCTO_id_producto) REFERENCES PRODUCTO (id_producto);
-- relacion ALMACENA del MER
ALTER TABLE DETALLE_SUMINISTRO ADD CONSTRAINT DETALLE_SUMINISTRO_SUMINISTRO_FK FOREIGN KEY (SUMINISTRO_id_suministro) REFERENCES SUMINISTRO (id_suministro);
-- relacion INCLUYE del MER
ALTER TABLE DETALLE_SUMINISTRO ADD CONSTRAINT DETALLE_SUMINISTRO_PRODUCTO_FK FOREIGN KEY (PRODUCTO_id_producto) REFERENCES PRODUCTO (id_producto);
-- relacion INCLUYE del MER

