    estado_registro CHAR(1) DEFAULT 'A' NOT NULL
);

ALTER TABLE LOCAL ADD CONSTRAINT PK_LOCAL PRIMARY KEY (id_local);

CREATE TABLE PRODUCTO (
    id_producto INTEGER NOT NULL,
    CATEGORIA_id_categoria INTEGER NOT NULL,
